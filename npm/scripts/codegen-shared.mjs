/**
 * Helpers shared by each package's codegen script, so every package embeds its
 * token list, marks its CommonJS build and tracks the list version the same way.
 */

import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const REPOSITORY_ROOT = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const GENERATED_HEADER = "// Auto-generated by codegen.mjs -- do not edit";

/**
 * Read a token list JSON file from the repository root.
 *
 * Exits the process with code 1 when the file is not valid JSON, so codegen
 * never embeds a broken list.
 *
 * @param {string} fileName - File name relative to the repository root, e.g. "tokenlist-mainnet.json".
 * @returns {{ json: string, version: { major: number, minor: number, patch: number } }} The raw
 *   file text and the list's version.
 */
export function readTokenListJson(fileName) {
  const json = readFileSync(join(REPOSITORY_ROOT, fileName), "utf-8");

  try {
    return { json, version: JSON.parse(json).version };
  } catch (error) {
    console.error(`codegen: ${fileName} is not valid JSON:`, error.message);
    process.exit(1);
  }
}

/**
 * Write a generated TypeScript module, prefixed with the do-not-edit header.
 *
 * Creates the parent directory when missing.
 *
 * @param {string} path - Absolute path of the module to write.
 * @param {string[]} lines - Module body, one entry per line.
 */
export function writeGeneratedModule(path, lines) {
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, [GENERATED_HEADER, ...lines, ""].join("\n"));
}

/**
 * Build the body of a module that embeds a token list.
 *
 * `satisfies` checks the data against the types at build time; exporting the
 * widened type keeps a literal type of every token out of the published .d.ts.
 *
 * @param {{ json: string, typeName: string, exportName: string }} options - The list's
 *   raw JSON, the type it must satisfy (exported from ./types.js), and the name to export it under.
 * @returns {string[]} Module body for writeGeneratedModule.
 */
export function buildTokenListModule({ json, typeName, exportName }) {
  return [
    `import type { ${typeName} } from "./types.js";`,
    "",
    `const tokenList = ${json.trimEnd()} as const satisfies ${typeName};`,
    "",
    `export const ${exportName}: ${typeName} = tokenList;`,
  ];
}

/**
 * Write dist/cjs/package.json so Node loads the CommonJS build as CommonJS
 * inside a "type": "module" package.
 *
 * @param {string} packageDirectory - Absolute path of the npm package.
 */
export function writeCommonJsMarker(packageDirectory) {
  const commonJsDirectory = join(packageDirectory, "dist", "cjs");
  mkdirSync(commonJsDirectory, { recursive: true });
  writeFileSync(
    join(commonJsDirectory, "package.json"),
    `${JSON.stringify({ type: "commonjs" }, null, 2)}\n`,
  );
}

/**
 * Set the package's version to the token list's version.
 *
 * Rewrites package.json in place.
 *
 * @param {string} packageDirectory - Absolute path of the npm package.
 * @param {{ major: number, minor: number, patch: number }} listVersion - The token list's version object.
 * @returns {string} The version written, e.g. "2.49.0".
 */
export function syncPackageVersion(packageDirectory, listVersion) {
  const version = `${listVersion.major}.${listVersion.minor}.${listVersion.patch}`;
  const manifestPath = join(packageDirectory, "package.json");
  const manifest = JSON.parse(readFileSync(manifestPath, "utf-8"));

  manifest.version = version;
  writeFileSync(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`);

  return version;
}
