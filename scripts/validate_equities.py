#!/usr/bin/env python3
"""Validate tokenlist-equities.json.

The file is generated by sync_equities.py, so this guards against hand edits
and bad syncs: it checks the structure of every entry and compares name,
symbol and decimals with on-chain values.
"""

import argparse
import re
import sys
from collections.abc import Mapping
from typing import Literal

import validate_tokens
from utils.coingecko import COINGECKO_ID_PATTERN
from utils.equities import (
    EQUITIES_LIST_FILE,
    EQUITIES_LIST_PATH,
    EquityToken,
    parse_equity_token,
    print_onchain_progress,
)
from utils.json_values import read_object_list
from utils.token_list import find_duplicate_errors, load_existing_token_list
from utils.web3 import (
    CHAIN_ID,
    add_rpc_url_argument,
    fetch_token_metadata_in_batches,
    get_web3_connection,
)
from web3 import Web3

REQUIRED_FIELDS = [*validate_tokens.REQUIRED_FIELDS, "tags", "logoURI"]
ALLOWED_FIELDS = validate_tokens.ALLOWED_TOP_LEVEL_FIELDS | {"tags", "logoURI"}
# Typed as literals so each field can index TokenMetadata.
TOKEN_METADATA_FIELDS: tuple[Literal["name", "symbol", "decimals"], ...] = (
    "name",
    "symbol",
    "decimals",
)

TAG_ID_PATTERN = re.compile(r"^\w{1,10}$")
TAG_NAME_PATTERN = re.compile(r"^[ \w]{1,20}$")
TAG_DESCRIPTION_PATTERN = re.compile(r"^[ \w.,:]{1,200}$")
MAX_TAGS = 20


def check_token_entry(
    entry: Mapping[str, object], tag_ids: set[str]
) -> tuple[EquityToken | None, list[str]]:
    """Check one token entry's structure without touching the chain.

    Args:
        entry: A token list entry as decoded from JSON.
        tag_ids: Tag IDs defined in the list's tags map.

    Returns:
        tuple[EquityToken | None, list[str]]: The typed entry, or None when its
        fields are missing or mistyped; and error messages, empty when it is valid.
    """
    label = entry.get("symbol", entry.get("address", "<unknown token>"))
    missing_fields = [field for field in REQUIRED_FIELDS if field not in entry]

    if missing_fields:
        return None, [f"{label}: missing field(s) {', '.join(missing_fields)}"]

    errors = [
        f"{label}: unexpected field {field!r}" for field in entry if field not in ALLOWED_FIELDS
    ]
    extension_errors = validate_tokens.validate_extensions(entry.get("extensions", {}))
    errors.extend(f"{label}: {error}" for error in extension_errors)

    if errors:
        return None, errors

    try:
        token = parse_equity_token(entry)
    except ValueError as e:
        return None, [f"{label}: {e}"]

    return token, [f"{label}: {error}" for error in find_typed_token_errors(token, tag_ids)]


def find_typed_token_errors(token: EquityToken, tag_ids: set[str]) -> list[str]:
    """Check the values of an entry whose fields have the right types.

    Args:
        token: A token list entry, typed.
        tag_ids: Tag IDs defined in the list's tags map.

    Returns:
        list[str]: Error messages without the token label; empty when the entry is valid.
    """
    errors = []

    if token["chainId"] != CHAIN_ID:
        errors.append(f"chainId is {token['chainId']}, expected {CHAIN_ID}")

    if not Web3.is_checksum_address(token["address"]):
        errors.append(f"address {token['address']} is not checksummed")

    if not token["logoURI"].startswith("https://"):
        errors.append("logoURI must be an https URL")

    if not token["tags"]:
        errors.append("needs an issuer tag")

    errors.extend(f"undefined tag {tag!r}" for tag in token["tags"] if tag not in tag_ids)
    coin_gecko_id = token.get("extensions", {}).get("coinGeckoId")

    if coin_gecko_id is not None and not COINGECKO_ID_PATTERN.match(coin_gecko_id):
        errors.append(f"coinGeckoId {coin_gecko_id!r} is not a CoinGecko ID")

    return errors


def find_token_metadata_mismatches(
    web3: Web3,
    tokens: list[EquityToken],
) -> list[str]:
    """Compare each token's name, symbol and decimals with its on-chain values.

    Args:
        web3: Web3 instance connected to the chain.
        tokens: Token list entries with checksummed addresses.

    Returns:
        list[str]: One message per mismatch or unreadable contract; empty when all match.
    """
    metadata, fetch_errors = fetch_token_metadata_in_batches(
        web3, [token["address"] for token in tokens], print_onchain_progress
    )
    messages = [
        f"{address}: cannot read metadata ({error})" for address, error in fetch_errors.items()
    ]

    for token in tokens:
        onchain = metadata.get(token["address"])

        if onchain is None:
            continue

        messages.extend(
            f"{token['symbol']}: {field} is {token[field]!r}, on-chain {onchain[field]!r}"
            for field in TOKEN_METADATA_FIELDS
            if token[field] != onchain[field]
        )

    return messages


def find_tag_definition_errors(tags: Mapping[str, object]) -> list[str]:
    """Check the list-level tag definitions against the token list schema's limits.

    Args:
        tags: The list's tags object as decoded from JSON, mapping tag ID to its
            name and description.

    Returns:
        list[str]: One message per violation; empty when all definitions are valid.
    """
    errors = [f"too many tags: {len(tags)} (max {MAX_TAGS})"] if len(tags) > MAX_TAGS else []

    for tag_id, definition in tags.items():
        name = definition.get("name") if isinstance(definition, dict) else None
        description = definition.get("description") if isinstance(definition, dict) else None

        if not TAG_ID_PATTERN.match(tag_id):
            errors.append(f"tag ID {tag_id!r} must be 1-10 word characters")

        if not isinstance(name, str) or not TAG_NAME_PATTERN.match(name):
            errors.append(f"tag {tag_id!r}: name must be 1-20 letters, digits, _ or spaces")

        if not isinstance(description, str) or not TAG_DESCRIPTION_PATTERN.match(description):
            errors.append(
                f"tag {tag_id!r}: description must be 1-200 letters, digits, spaces or _ . , :"
            )

    return errors


def main() -> int:
    """Main entry point for the tokenized equities list validator.

    Returns:
        int: Exit code (0 for success, 1 for failure).
    """
    parser = argparse.ArgumentParser(description="Validate tokenlist-equities.json")
    add_rpc_url_argument(parser)
    parser.add_argument(
        "--skip-onchain",
        action="store_true",
        help="Only check the file's structure",
    )
    args = parser.parse_args()

    try:
        token_list = load_existing_token_list(EQUITIES_LIST_PATH)

        if token_list is None:
            print(f"{EQUITIES_LIST_FILE} is missing")
            return 1

        entries = read_object_list(token_list, "tokens")
        tags = token_list.get("tags", {})

        if not isinstance(tags, dict):
            print("tags must be a JSON object")
            return 1

        print(f"Validating {len(entries)} token(s) in {EQUITIES_LIST_FILE}...")
        tag_ids = set(tags)
        tokens: list[EquityToken] = []
        errors = find_tag_definition_errors(tags) + find_duplicate_errors(entries)

        for entry in entries:
            token, entry_errors = check_token_entry(entry, tag_ids)
            errors.extend(entry_errors)

            if token is not None:
                tokens.append(token)

        if not errors and not args.skip_onchain:
            web3 = get_web3_connection(args.rpc_url)
            print("Comparing name, symbol and decimals with on-chain values...", flush=True)
            errors.extend(find_token_metadata_mismatches(web3, tokens))

        if errors:
            for error in errors:
                print(f"   - {error}")

            print(f"\nValidation failed with {len(errors)} error(s)")
            return 1

        print(f"\nAll {len(entries)} token(s) are valid")
        return 0
    except (ConnectionError, OSError, ValueError, KeyError) as e:
        print(e)
        return 1


if __name__ == "__main__":
    sys.exit(main())
